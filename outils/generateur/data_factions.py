def arme(item, nom, couleur, atk=None, vit=None, lore=(), ench=None, **kw):
    d = {"id": item, "nom": nom, "c": couleur, "lore": list(lore), "ench": ench or {}}
    if atk is not None:
        d["atk"] = (atk, vit)
    d.update(kw)
    return d


def piece(item, nom, couleur, dye=None, trim=None, lore=(), ench=None, **kw):
    d = {"id": item, "nom": nom, "c": couleur, "lore": list(lore), "ench": ench or {}}
    if dye is not None:
        d["dye"] = dye
    if trim:
        d["trim"] = trim
    d.update(kw)
    return d


def objet(item, n=1, nom=None, c="white", lore=()):
    d = {"id": item, "n": n, "lore": list(lore)}
    if nom:
        d["nom"] = nom
        d["c"] = c
    return d


